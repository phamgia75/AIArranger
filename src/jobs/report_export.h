// The report as a NEW folder through the E6 job runner. The report's source (a library folder or a report file) is a
// job source, so the output may not be, contain or lie inside it (D18; owner libraries stay read-only).
inline ExportSpec reportExport(std::shared_ptr<const report::Report> r, fs::path dest) {
    ExportSpec s;
    s.type = "Report (HTML + CSV)";
    s.source = r ? r->source : std::string();
    if (r && !r->source.empty()) s.sources = {r->source};
    s.dest = std::move(dest);
    s.validate = [r] { return r ? std::string() : std::string("refusing: no report is open"); };
    s.dependencies = [](auto& notes, auto&) {
        notes.push_back("A report document: its source was only read and no keyboard file is written");
        return std::vector<std::string>{};
    };
    s.preview = [r] {
        std::vector<OutFile> f;
        for (const auto& [rel, b] : report::files(*r)) f.push_back({rel, b.size(), "", true});
        f.push_back({"PACKAGE.sha256", 4096, "", false});
        return f;
    };
    s.write = [r](const fs::path& out, auto&) {
        const auto e = media::samplelab::writeLabFolder(out, report::files(*r));
        return e.empty() ? WriteResult{"", r->title + ": report.html + " + std::to_string(r->tables.size()) + " CSV file(s). " + report::kNotice}
                         : WriteResult{"Report NOT written: " + e, ""};
    };
    s.verify = [r](const fs::path& out) {
        const auto c = media::sound::verifyPackage(out);
        Verification v;
        v.l1 = ui::studio::fromPackageCheck(c).l1;
        std::string text = c.text;
        if (v.l1.state == Check::Passed) {
            if (const auto e = report::checkFolder(out, *r); !e.empty()) {
                v.l1 = {Check::Failed, "report check: " + e};
                text = "NOT verified: " + e;
            } else {
                text = "L1: the files match PACKAGE.sha256; every CSV parses back to its table; report.html holds only its own tags "
                       "(no script, no external reference). L2 not applicable (a report document). L3 never: nothing for the keyboard was written.";
            }
        }
        v.l2 = {Check::NotRun, "not applicable: a report document"};
        return std::pair<Verification, std::string>{v, text};
    };
    return s;
}

