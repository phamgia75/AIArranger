inline constexpr const char* kNotice =
    "Generated by AIArranger from its own report data (the source was only read). Not verified on a Pa5X: nothing in "
    "this report was tested on a keyboard.";
inline constexpr uintmax_t kMaxJsonBytes = uintmax_t(10) << 20;   // a report file larger than 10 MiB is refused

struct Table {
    std::string id, title;   // id: the CSV file name without ".csv" (fixed ASCII names chosen here, never user text)
    std::vector<std::string> columns;
    std::vector<std::vector<std::string>> rows;
};
struct Report {
    std::string kind, title, source;   // source: the file or folder it was made from (only read)
    std::vector<std::pair<std::string, std::string>> facts;
    std::vector<Table> tables;
};

// ── HTML ──
inline std::string htmlEscape(const std::string& s) {
    std::string o;
    o.reserve(s.size());
    for (const char c : s) {
        switch (c) {
            case '&': o += "&amp;"; break;
            case '<': o += "&lt;"; break;
            case '>': o += "&gt;"; break;
            case '"': o += "&quot;"; break;
            case '\'': o += "&#39;"; break;
            default: o += c;
        }
    }
    return o;
}

inline std::string html(const Report& r) {
    const auto e = htmlEscape;
    std::string o =
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
        "<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'\">\n<title>" + e(r.title) +
        "</title>\n<style>\nbody{font:13px -apple-system,system-ui,sans-serif;margin:16px;color:#111;background:#fff}\n"
        "table{border-collapse:collapse;margin:8px 0 24px}\nth,td{border:1px solid #bbb;padding:2px 6px;text-align:left;vertical-align:top;"
        "white-space:pre-wrap}\nth{background:#eee}\ndd{white-space:pre-wrap;margin:0 0 6px 16px}\ndt{font-weight:bold}\n.notice{font-weight:bold}\n"
        "</style>\n</head>\n<body>\n<h1>" + e(r.title) + "</h1>\n<p class=\"notice\">" + e(kNotice) + "</p>\n<dl>\n<dt>Source</dt><dd>" + e(r.source) + "</dd>\n";
    for (const auto& [k, v] : r.facts) o += "<dt>" + e(k) + "</dt><dd>" + e(v) + "</dd>\n";
    o += "</dl>\n";
    for (const auto& t : r.tables) {
        o += "<h2>" + e(t.title) + " (" + std::to_string(t.rows.size()) + ")</h2>\n<table>\n<thead><tr>";
        for (const auto& c : t.columns) o += "<th>" + e(c) + "</th>";
        o += "</tr></thead>\n<tbody>\n";
        for (const auto& row : t.rows) {
            o += "<tr>";
            for (const auto& c : row) o += "<td>" + e(c) + "</td>";
            o += "</tr>\n";
        }
        o += "</tbody>\n</table>\n";
    }
    return o + "</body>\n</html>\n";
}

// "" when `h` holds only the tags html() emits (so nothing can load a script, image, font, style sheet or URL), else
// the first offending tag or style rule. Independent of html(): it scans the bytes, it does not compare with them.
inline std::string htmlRefusal(const std::string& h) {
    static const std::set<std::string> allowed = {
        "!DOCTYPE html", "html lang=\"en\"", "/html", "head", "/head", "meta charset=\"utf-8\"",
        "meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'\"", "title", "/title", "style", "/style",
        "body", "/body", "h1", "/h1", "h2", "/h2", "p class=\"notice\"", "/p", "dl", "/dl", "dt", "/dt", "dd", "/dd", "table", "/table",
        "thead", "/thead", "tbody", "/tbody", "tr", "/tr", "th", "/th", "td", "/td"};
    bool inStyle = false;
    size_t styleFrom = 0;
    for (size_t i = 0; i < h.size(); ++i) {
        if (h[i] == '>') return "a '>' outside a tag at byte " + std::to_string(i);
        if (h[i] != '<') continue;
        const size_t end = h.find('>', i);
        if (end == std::string::npos) return "an unterminated tag at byte " + std::to_string(i);
        const std::string tag = h.substr(i + 1, end - i - 1);
        if (!allowed.count(tag)) return "tag <" + tag.substr(0, 60) + "> is not one this writer emits";
        if (tag == "style") { inStyle = true; styleFrom = end + 1; }
        if (tag == "/style") {
            if (!inStyle) return "</style> without <style>";
            const std::string css = media::detail::lower(h.substr(styleFrom, i - styleFrom));
            for (const char* bad : {"url(", "@import", "@font-face", "expression(", "\\"})
                if (css.find(bad) != std::string::npos) return std::string("style holds ") + bad;
            inStyle = false;
        }
        i = end;
    }
    return inStyle ? "an unclosed <style>" : "";
}

// ── CSV (RFC 4180) ──
inline std::string csvCell(const std::string& v) {
    std::string c = v;
    if (!c.empty() && c[0] != '\0' && std::strchr("=+-@\t\r'", c[0])) c.insert(c.begin(), '\'');   // formula-injection guard
    if (c.find_first_of(",\"\r\n") == std::string::npos) return c;
    std::string q = "\"";
    for (const char ch : c) q += ch == '"' ? std::string("\"\"") : std::string(1, ch);
    return q + "\"";
}

inline std::string csv(const Table& t) {
    std::string o;
    const auto line = [&](const std::vector<std::string>& cells) {
        for (size_t i = 0; i < cells.size(); ++i) o += (i ? "," : "") + csvCell(cells[i]);
        o += "\r\n";
    };
    line(t.columns);
    for (const auto& r : t.rows) line(r);
    return o;
}

// Strict RFC 4180 reader (CRLF or LF records; a quote only at the start of a field), stripping the one leading ' that
// csvCell adds. "" and *rows set, or why `text` is not such a CSV.
inline std::string parseCsv(const std::string& text, std::vector<std::vector<std::string>>* rows) {
    rows->clear();
    std::vector<std::string> row;
    std::string field;
    bool quoted = false;
    const auto endField = [&] {
        if (!field.empty() && field[0] == '\'') field.erase(0, 1);
        row.push_back(std::move(field));
        field.clear();
        quoted = false;
    };
    for (size_t i = 0; i < text.size(); ++i) {
        const char c = text[i];
        if (c == '"' && field.empty() && !quoted) {   // a quoted field
            quoted = true;
            for (++i;; ++i) {
                if (i >= text.size()) return "unterminated quoted field";
                if (text[i] != '"') { field += text[i]; continue; }
                if (i + 1 < text.size() && text[i + 1] == '"') { field += '"'; ++i; continue; }
                break;
            }
            if (i + 1 < text.size() && text[i + 1] != ',' && text[i + 1] != '\r' && text[i + 1] != '\n')
                return "bytes after a closing quote at byte " + std::to_string(i + 1);
            continue;
        }
        if (c == '"') return "a quote inside an unquoted field at byte " + std::to_string(i);
        if (c == ',') { endField(); continue; }
        if (c == '\r' || c == '\n') {
            if (c == '\r' && (i + 1 >= text.size() || text[i + 1] != '\n')) return "a CR without LF at byte " + std::to_string(i);
            if (c == '\r') ++i;
            endField();
            rows->push_back(std::move(row));
            row.clear();
            continue;
        }
        if (quoted) return "bytes after a closing quote at byte " + std::to_string(i);
        field += c;
    }
    if (!field.empty() || quoted || !row.empty()) { endField(); rows->push_back(std::move(row)); }
    return "";
}

// ── Viewer text ──
// shortcut: the viewer shows at most `maxRows` rows per table (the export has all); a table widget if that is too few.
inline std::string text(const Report& r, size_t maxRows = 2000) {
    std::string o = r.title + "\n" + kNotice + "\nSource: " + r.source + "\n";
    for (const auto& [k, v] : r.facts) o += k + ": " + v + "\n";
    for (const auto& t : r.tables) {
        o += "\n== " + t.title + " (" + std::to_string(t.rows.size()) + ") ==\n";
        for (size_t i = 0; i < t.columns.size(); ++i) o += (i ? " | " : "") + t.columns[i];
        o += "\n";
        for (size_t k = 0; k < t.rows.size() && k < maxRows; ++k) {
            for (size_t i = 0; i < t.rows[k].size(); ++i) o += (i ? " | " : "") + t.rows[k][i];
            o += "\n";
        }
        if (t.rows.size() > maxRows) o += "... " + std::to_string(t.rows.size() - maxRows) + " more rows (all are in the HTML / CSV export)\n";
    }
    return o;
}

// ── From the existing structs ──
inline std::string slot1(long long s) { return s >= 0 ? std::to_string(s + 1) : ""; }   // 0-based -> shown 1-based, "" = none

inline Report fromInventory(const library::Library& L) {
    using std::to_string;
    Report r{"inventory", "Library inventory: " + L.name, L.root, {}, {}};
    if (!L.ok) { r.facts = {{"Not read", L.error}}; return r; }
    r.facts = {{"Format", library::formatName(L.format)},
               {"Layout", L.layout + " (from the folder layout and file names)"},
               {"Files", to_string(L.files.size())},
               {"Items", to_string(L.items.size())},
               {"Banks", to_string(L.banks.size())},
               {"Total bytes", to_string(L.bytes)},
               {"Sample data on disk (.PCM + .KMP file sizes, not keyboard sample RAM)", to_string(L.sampleFiles) + " files, " + to_string(L.sampleDiskBytes) + " bytes"},
               {"Skipped (links and special files, not followed)", to_string(L.skipped.size())}};
    if (L.format == library::Format::PaSet)
        r.facts.push_back({"Items from", "the Pa-native reader (READ-ONLY, EXPERIMENTAL; layout observed on one owner Pa700 SET)"});
    if (L.format == library::Format::Pa5xKst)
        r.facts.push_back({"Items from", "file names (one item per file); KST file content is not decoded (container UNKNOWN)"});
    Table items{"items", "Items", {"type", "bank", "slot (1-based)", "name", "file", "bytes", "from"}, {}};
    for (const auto& it : L.items) items.rows.push_back({it.type, it.bank, slot1(it.slot), it.name, it.file, to_string(it.bytes), it.from});
    Table banks{"banks", "Banks", {"bank", "type", "files", "items", "slots per bank file (MAN4 p.975)", "bytes"}, {}};
    for (const auto& [id, b] : L.banks) {
        const int cap = library::bankCapacity(L.format, b.type);
        banks.rows.push_back({id, b.type, to_string(b.files), to_string(b.items), cap ? to_string(cap) : "", to_string(b.bytes)});
    }
    Table files{"files", "Files", {"path", "bytes", "sha256", "container"}, {}};
    for (const auto& [rel, f] : L.files) files.rows.push_back({rel, to_string(f.size), f.sha256, f.container});
    Table deps{"dependencies", "Dependencies (only where evidenced)", {"status", "from", "to", "reason"}, {}};
    for (const auto& d : L.deps) deps.rows.push_back({d.status, d.from, d.to, d.reason});
    Table skipped{"skipped", "Skipped (not followed)", {"path"}, {}};
    for (const auto& s : L.skipped) skipped.rows.push_back({s});
    r.tables = {items, banks, files, deps, skipped};
    return r;
}

inline Report fromValidation(const library::Validation& v) {
    using std::to_string;
    Report r{"validation", "Structural validation: " + media::folderPath(v.root).filename().string(), v.root, {}, {}};
    if (!v.ok) { r.facts = {{"NOT validated", v.error}}; return r; }
    r.facts = {{"Layout", v.layout},
               {"Rule table", v.table},
               {"Errors", to_string(v.count(library::Severity::Error))},
               {"Warnings", to_string(v.count(library::Severity::Warn))},
               {"Info", to_string(v.count(library::Severity::Info))},
               {"Scope", "File-level check only: content not decoded; not verified on a keyboard. Each finding names its rule's source."}};
    Table t{"findings", "Findings", {"severity", "rule", "path", "message", "source"}, {}};
    for (const auto& f : v.findings) t.rows.push_back({library::severityName(f.severity), f.rule, f.path, f.message, f.source});
    r.tables = {t};
    return r;
}

// ── From the existing JSON (plan.json, NAME.export.json) ──
namespace detail {
inline std::string val(const Json* j) {
    if (!j) return "";
    if (j->t == Json::T::Str || j->t == Json::T::Num) return j->s;
    if (j->t == Json::T::Bool) return j->b ? "true" : "false";
    if (j->t == Json::T::Arr) {
        std::string o;
        for (size_t i = 0; i < j->a.size(); ++i) o += (i ? "\n" : "") + val(&j->a[i]);
        return o;
    }
    return "";
}
inline std::string slotOf(const Json* j) {
    if (!j || j->t != Json::T::Num) return "";
    char* end = nullptr;
    const long long n = std::strtoll(j->s.c_str(), &end, 10);
    return end && *end == '\0' ? slot1(n) : "";
}
inline const Json* at(const Json& o, const char* k) { return o.t == Json::T::Obj ? o.get(k) : nullptr; }
}  // namespace detail

inline Report fromPlanJson(const Json& j, const std::string& source) {
    using detail::at;
    using detail::val;
    Report r{"plan", "Library Manager plan (EXPORT-ONLY)", source, {}, {}};
    r.facts = {{"Status", val(at(j, "status"))}, {"Apply", val(at(j, "apply")) + ": " + val(at(j, "apply_reason"))}};
    if (const Json* libs = at(j, "libraries"))
        for (const char* side : {"A", "B"})
            if (const Json* L = at(*libs, side))
                r.facts.push_back({std::string("Library ") + side, val(at(*L, "path")) + " (" + val(at(*L, "format")) + ", " + val(at(*L, "layout")) + ", " +
                                                                       val(at(*L, "files")) + " files, " + val(at(*L, "bytes")) + " bytes)"});
    Table t{"steps", "Steps", {"n", "op", "side", "item type", "item bank", "item slot (1-based)", "item name", "item file", "item file sha256",
                               "to bank", "to slot (1-based; empty = first free)", "new name", "banks swapped", "whole bank file", "summary", "conflicts", "warnings"}, {}};
    if (const Json* steps = at(j, "steps"); steps && steps->t == Json::T::Arr)
        for (const auto& s : steps->a) {
            const Json* it = at(s, "item");
            const auto iv = [&](const char* k) { return it ? val(at(*it, k)) : std::string(); };
            t.rows.push_back({val(at(s, "n")), val(at(s, "op")), val(at(s, "side")), iv("type"), iv("bank"), it ? detail::slotOf(at(*it, "slot")) : "",
                              iv("name"), iv("file"), iv("file_sha256"), val(at(s, "to_bank")), detail::slotOf(at(s, "to_slot")), val(at(s, "new_name")),
                              val(at(s, "banks")), val(at(s, "whole_file")), val(at(s, "summary")), val(at(s, "conflicts")), val(at(s, "warnings"))});
        }
    r.tables = {t};
    return r;
}

inline Report fromExportJson(const Json& j, const std::string& source) {
    using detail::at;
    using detail::val;
    Report r{"export", "Export report: " + val(at(j, "type")), source, {}, {}};
    r.facts = {{"Schema", val(at(j, "schema"))}, {"Job", val(at(j, "job"))},      {"Source (only read)", val(at(j, "source"))},
               {"Output", val(at(j, "output"))}, {"Result", val(at(j, "result"))}, {"Reason", val(at(j, "reason"))}};
    if (const Json* s = at(j, "status")) r.facts.push_back({"Conversion status", val(s)});
    r.facts.push_back({"Planned bytes", val(at(j, "plannedBytes"))});
    r.facts.push_back({"Sample bytes", val(at(j, "sampleBytes"))});
    if (const Json* v = at(j, "verification"))
        for (const char* l : {"L1", "L2", "L3"})
            if (const Json* x = at(*v, l)) r.facts.push_back({std::string("Verification ") + l, val(at(*x, "state")) + ": " + val(at(*x, "detail"))});
    r.facts.push_back({"Writer report", val(at(j, "writer"))});
    r.facts.push_back({"Verification text", val(at(j, "verifyText"))});
    Table files{"files", "Files", {"path", "bytes", "sha256"}, {}};
    if (const Json* f = at(j, "files"); f && f->t == Json::T::Arr)
        for (const auto& x : f->a) files.rows.push_back({val(at(x, "path")), val(at(x, "bytes")), val(at(x, "sha256"))});
    Table conv{"conversion", "Conversion (EXACT / MEASURED / ESTIMATED / MISSING)", {"class", "item"}, {}};
    if (const Json* c = at(j, "conversion"); c && c->t == Json::T::Arr)
        for (const auto& x : c->a) conv.rows.push_back({val(at(x, "class")), val(at(x, "item"))});
    Table msgs{"messages", "Missing resources, warnings and notes", {"kind", "text"}, {}};
    for (const char* k : {"missing", "warnings", "notes"})
        if (const Json* m = at(j, k); m && m->t == Json::T::Arr)
            for (const auto& x : m->a) msgs.rows.push_back({k, val(&x)});
    r.tables = {files, conv, msgs};
    return r;
}

// "" and *out set from a plan.json or NAME.export.json text, or why it is neither.
inline std::string fromJsonText(const std::string& text, const std::string& source, Report* out) {
    Json j;
    if (const auto e = parseJson(text, &j); !e.empty()) return "not valid JSON: " + e;
    if (detail::val(detail::at(j, "format")) == "aiarranger-library-plan") { *out = fromPlanJson(j, source); return ""; }
    if (detail::val(detail::at(j, "schema")) == "aiarranger-export-report/1") { *out = fromExportJson(j, source); return ""; }
    return "not an AIArranger plan.json (aiarranger-library-plan) or export report (aiarranger-export-report/1)";
}

// A regular file (no symlink followed) of at most `limit` bytes. "" and *out set, or why not. Read-only.
inline std::string readFile(const fs::path& p, uintmax_t limit, std::string* out) {
    std::FILE* f = media::detail::openRegular(AT_FDCWD, p.c_str());
    if (!f) return "cannot read " + p.string() + " (missing, or not a regular file)";
    out->clear();
    char buf[65536];
    size_t n;
    while ((n = std::fread(buf, 1, sizeof buf, f)) > 0) {
        if (out->size() + n > limit) { std::fclose(f); return p.filename().string() + " is larger than " + std::to_string(limit) + " bytes"; }
        out->append(buf, n);
    }
    const bool err = std::ferror(f);
    std::fclose(f);
    return err ? "cannot read " + p.string() : "";
}

// Worker thread: a plan.json or NAME.export.json file as a Report.
inline std::string loadJsonReport(const fs::path& p, Report* out) {
    std::string text;
    if (auto e = readFile(p, kMaxJsonBytes, &text); !e.empty()) return e;
    return fromJsonText(text, p.string(), out);
}

// ── The output folder (report.html + one CSV per table) and its independent check ──
inline std::vector<std::pair<std::string, std::vector<uint8_t>>> files(const Report& r) {
    std::vector<std::pair<std::string, std::vector<uint8_t>>> f{{"report.html", media::samplelab::bytesOf(html(r))}};
    for (const auto& t : r.tables) f.push_back({t.id + ".csv", media::samplelab::bytesOf(csv(t))});
    return f;
}

// "" when the folder's HTML has only this writer's tags and every CSV parses back to exactly its table.
inline std::string checkFolder(const fs::path& dir, const Report& r) {
    std::string h;
    if (auto e = readFile(dir / "report.html", uintmax_t(1) << 32, &h); !e.empty()) return e;
    if (auto e = htmlRefusal(h); !e.empty()) return "report.html: " + e;
    for (const auto& t : r.tables) {
        std::string c;
        if (auto e = readFile(dir / (t.id + ".csv"), uintmax_t(1) << 32, &c); !e.empty()) return e;
        std::vector<std::vector<std::string>> rows;
        if (auto e = parseCsv(c, &rows); !e.empty()) return t.id + ".csv: " + e;
        std::vector<std::vector<std::string>> want{t.columns};
        want.insert(want.end(), t.rows.begin(), t.rows.end());
        if (rows != want) return t.id + ".csv does not parse back to its table";
    }
    return "";
}

