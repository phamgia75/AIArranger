// P1 report export (parity C17, C18): the existing reports as self-contained HTML and CSV, and the model the in-app
// report viewer shows. Every report is built from the existing structs or JSON, never by re-parsing human text:
//   - library inventory: library::Library (E7, library_model.h)
//   - validation findings: library::Validation (E8, library_validate.h; every finding carries its rule's source)
//   - Library Manager plan: plan.json (library_plan.h planJson, "aiarranger-library-plan" v1)
//   - export / conversion report: NAME.export.json (export_job.h reportJson, "aiarranger-export-report/1")
// The existing PLAN.txt / plan.json / NAME.export.* files are untouched; this only reads them.
//
// HTML: one file, no script, no external reference (no link, image, font, URL or network; a CSP meta forbids them);
// every text escaped. CSV: RFC 4180 (CRLF, quotes doubled, a field with , " CR or LF quoted), one file per table;
// formula-injection safe: a cell starting with = + - @ TAB CR gets a leading ' (OWASP CSV injection), and so does a
// cell starting with ' itself, so parseCsv strips exactly one leading ' and the round trip is lossless.
// Written only through the E6 job runner (reportExport: NAME.INCOMPLETE, PACKAGE.sha256, independent check of the
// staged files: every CSV parsed back equals its table, the HTML holds only the tags this writer emits, then publish).

#include "jobs/import_kit.h"            // parseJson, Json; export_job.h; package_verify.h
